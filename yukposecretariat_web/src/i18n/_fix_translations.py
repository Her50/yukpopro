def apply(lang: str) -> int:
    fname = f"{lang}.json"
    data = load(fname)
    overrides = TR[lang]
    n = 0
    for section, kv in overrides.items():
        if section not in data:
            continue
        for key, val in kv.items():
            if key in data[section] and data[section][key] != val:
                data[section][key] = val
                n += 1
    dump(fname, data)
    return n


